	Given a string s and an integer k, return the maximum number of vowel letters in any substring of s with length k.

	Vowel letters in English are 'a', 'e', 'i', 'o', and 'u'.

	Example 1:

	Input: s = "abciiidef"; k = 3
	Output: 3
	Explanation: The substring "iii" contains 3 vowel letters.

	Example 2:

	Input: s = "aeiou"; k = 2
	Output: 2
	Explanation: Any substring of length 2 contains 2 vowels.

	Example 3:

	Input: s = "leetcode"; k = 3
	Output: 2
	Explanation: "lee", "eet" and "ode" contain 2 vowels.

	sliding window technique. This approach is efficient and works in linear time 𝑂(𝑛), where 𝑛 is the length of the string.

	🧠 How It Works:
		Initialize a window of size k and count how many vowels are in it.

		Slide the window one character at a time:

		Add the new rightmost character if it's a vowel.

		Subtract the leftmost character (falling out of the window) if it's a vowel.

		Track the maximum vowel count seen during any window.

	def max_vowels(s, k)
	  vowels = Set.new(['a', 'e', 'i', 'o', 'u'])
	  count = 0
	  max_count = 0

	  # Initial window of size k
	  (0...k).each do |i|
	    count += 1 if vowels.include?(s[i])
	  end
	  max_count = count

	  # Slide the window
	  (k...s.length).each do |i|
	    count += 1 if vowels.include?(s[i])
	    count -= 1 if vowels.include?(s[i - k])
	    max_count = [max_count, count].max
	  end

	  max_count
	end

